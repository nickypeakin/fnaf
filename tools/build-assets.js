#!/usr/bin/env node
// Regenerates every image in assets/img/ from the drawing code in tools/art/.
// Needs Playwright (npm i -D playwright && npx playwright install chromium).
// Usage: node tools/build-assets.js
'use strict';
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'assets', 'img');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  page.on('pageerror', (e) => { console.error('page error:', e.message); process.exitCode = 1; });
  await page.goto('file://' + path.join(__dirname, 'build-assets.html'));
  await page.evaluate(() => window.fontsReady);
  const assets = await page.evaluate(() => window.buildAssets());
  await browser.close();

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const manifest = {};
  let total = 0;
  for (const [name, { data, w, h }] of Object.entries(assets)) {
    const buf = Buffer.from(data.split(',')[1], 'base64');
    fs.writeFileSync(path.join(outDir, name + '.webp'), buf);
    manifest[name] = [w, h];
    total += buf.length;
  }
  // The game preloads everything listed here before the first night.
  fs.writeFileSync(path.join(root, 'js', 'assets-manifest.js'),
    '// Generated by tools/build-assets.js. Image name -> [width, height].\n' +
    `window.FN = window.FN || {};\nwindow.FN.ASSET_LIST = ${JSON.stringify(manifest, null, 0)};\n`);
  console.log(`wrote ${Object.keys(assets).length} images (${(total / 1024 / 1024).toFixed(2)} MB) to assets/img`);
})();
